uint8_t atan2_8(int16_t dy, int16_t dx)
{
    if (dx == 0 && dy == 0)
        return 0;
    int16_t ax = dx < 0 ? -dx : dx;
    int16_t ay = dy < 0 ? -dy : dy;
    /* Scale down so the products below stay in 16 bits. */
    while (ax > 255 || ay > 255) {
        ax >>= 1;
        ay >>= 1;
    }
    /* The slope as 0..32 per octant, bent toward atan() (error < 1). */
    uint8_t a;
    if (ax > ay) {
        uint8_t t = (uint8_t)(((uint16_t)ay * 32) / ax);
        a = (uint8_t)(t + (uint16_t)t * (32 - t) / 90);
    } else {
        uint8_t t = (uint8_t)(((uint16_t)ax * 32) / ay);
        a = (uint8_t)(64 - t - (uint16_t)t * (32 - t) / 90);
    }
    if (dx >= 0 && dy >= 0)
        return a;
    if (dx < 0 && dy >= 0)
        return (uint8_t)(128 - a);
    if (dx < 0)
        return (uint8_t)(128 + a);
    return (uint8_t)(256 - a);
}

uint8_t heading_to(int16_t dx, int16_t dy)
{
    /* Forward is (-sin, -cos): the heading of (dx, dy) is atan2(-dx, -dy),
     * which is 192 minus the standard angle of (dx, dy). */
    return (uint8_t)(192 - atan2_8(dy, dx));
}
